#!/usr/bin/env node

//
// Bundles scripts/validate-specs.js and its dependencies into one
// self-contained file that ships inside the `spec-validation` skill, so a model
// in any project (and any host) can validate specs without agent-tools'
// node_modules, a linked `agent-tools` command, or a copy of this repository.
// The output is committed; scripts/validator-bundle.test.js fails when it is
// out of date with the sources.
//

import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export const VALIDATOR_ENTRY = path.join(ROOT, "scripts", "validate-specs.js");
export const VALIDATOR_BUNDLE = path.join(ROOT, "core", "skills", "spec-validation", "validate-specs.mjs");

const BANNER =
  "// GENERATED by scripts/build-validator.js from scripts/validate-specs.js. Do not edit;\n" +
  "// change the source and run `npm run build:validator`.\n" +
  'import { createRequire as __createRequire } from "node:module";\n' +
  "const require = __createRequire(import.meta.url);\n";

export async function bundleValidator() {
  const result = await build({
    entryPoints: [VALIDATOR_ENTRY],
    bundle: true,
    platform: "node",
    format: "esm",
    target: "node20",
    write: false,
    legalComments: "none",
    banner: { js: BANNER },
    logLevel: "silent",
  });
  return result.outputFiles[0].text;
}

export async function writeValidatorBundle() {
  await fs.mkdir(path.dirname(VALIDATOR_BUNDLE), { recursive: true });
  await fs.writeFile(VALIDATOR_BUNDLE, await bundleValidator(), "utf8");
  return VALIDATOR_BUNDLE;
}

async function main() {
  console.log(`Wrote ${path.relative(ROOT, await writeValidatorBundle())}`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch(err => {
    console.error(err);
    process.exit(1);
  });
}
